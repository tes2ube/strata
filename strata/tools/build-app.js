// Builds Strata.html: index.html with every module under src/ bundled into one inline script.
// The result needs no server and no other file. Double-click it and it opens in your browser.
// No dependencies: a small bundler for the plain ES module syntax this project uses
// (named imports, one namespace import style, export function / const / class, export { a, b }).
// Run: node tools/build-app.js   (npm run build; npm test does it first)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve, relative, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ENTRY = 'src/render/app.js';
const SCRIPT_TAG = '<script type="module" src="src/render/app.js"></script>';

function parseModule(id, src) {
  const imports = [], exports = [];
  // imports: `import { a, b as c } from './x.js'`, `import * as X from './x.js'` (may span lines)
  src = src.replace(/^import\s+([\s\S]*?)\s+from\s+['"]([^'"]+)['"];?[ \t]*$/gm, (m, what, spec) => {
    const target = relative(ROOT, resolve(ROOT, dirname(id), spec)).split('\\').join('/');
    const ns = /^\*\s+as\s+([\w$]+)$/.exec(what.trim());
    if (ns) { imports.push({ target, names: null }); return `const ${ns[1]} = __req(${JSON.stringify(target)});`; }
    const named = /^\{([\s\S]*)\}$/.exec(what.trim());
    if (!named) throw new Error(`${id}: unsupported import form: import ${what}`);
    const parts = named[1].split(',').map((x) => x.trim()).filter(Boolean).map((x) => { const [a, b] = x.split(/\s+as\s+/); return { from: a.trim(), to: (b || a).trim() }; });
    imports.push({ target, names: parts.map((p) => p.from) });
    return `const { ${parts.map((p) => (p.from === p.to ? p.from : `${p.from}: ${p.to}`)).join(', ')} } = __req(${JSON.stringify(target)});`;
  });
  // exports
  src = src.replace(/^export\s+(async\s+function|function|class)\s+([\w$]+)/gm, (m, kind, name) => { exports.push([name, name]); return `${kind} ${name}`; });
  src = src.replace(/^export\s+(const|let|var)\s+([\w$]+)/gm, (m, kind, name) => { exports.push([name, name]); return `${kind} ${name}`; });
  src = src.replace(/^export\s*\{([^}]*)\};?[ \t]*$/gm, (m, list) => { for (const x of list.split(',').map((y) => y.trim()).filter(Boolean)) { const [a, b] = x.split(/\s+as\s+/); exports.push([(b || a).trim(), a.trim()]); } return ''; });
  if (/^export\s+default\b/m.test(src) || /^export\s+\*/m.test(src)) throw new Error(`${id}: export default and export * are not supported`);
  if (/^export\s+(?:const|let|var)\s+[^=\n]+=[^;\n]*,\s*[\w$]+\s*=/m.test(src)) throw new Error(`${id}: declare each export on its own line`);
  if (/^(?:import|export)\s/m.test(src)) throw new Error(`${id}: an import or export the bundler does not understand is left in the code`);
  return { src, imports, exports };
}

export function bundle(entry = ENTRY) {
  const mods = new Map();
  const visit = (id) => {
    if (mods.has(id)) return;
    const m = parseModule(id, readFileSync(join(ROOT, id), 'utf8')); mods.set(id, m);
    for (const imp of m.imports) visit(imp.target);
  };
  visit(entry);
  for (const [id, m] of mods) for (const imp of m.imports) if (imp.names) {
    const have = new Set(mods.get(imp.target).exports.map((e) => e[0]));
    for (const n of imp.names) if (!have.has(n)) throw new Error(`${id} imports "${n}" but ${imp.target} does not export it`);
  }
  const body = [...mods].map(([id, m]) => `__defs[${JSON.stringify(id)}] = function (__exp, __req) {\n${m.src}\n${m.exports.map(([out, local]) => `__exp.${out} = ${local};`).join(' ')}\n};`).join('\n');
  const js = `(function () {\n'use strict';\nconst __defs = {}, __cache = {};\nfunction __req(id) { if (__cache[id]) return __cache[id]; const exp = {}; __cache[id] = exp; __defs[id](exp, __req); return exp; }\n${body}\n__req(${JSON.stringify(entry)});\n})();`;
  return js.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');
}

export function buildHtml() {
  const html = readFileSync(join(ROOT, 'index.html'), 'utf8');
  if (!html.includes(SCRIPT_TAG)) throw new Error('index.html no longer has the module script tag the build replaces');
  return html.replace(SCRIPT_TAG, () => `<script>\n${bundle()}\n</script>`).replace('<head>', '<head>\n<!-- Strata.html is generated by tools/build-app.js from index.html and src/. Do not edit it by hand. -->');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = join(ROOT, 'Strata.html'), html = buildHtml();
  writeFileSync(out, html);
  console.log(`wrote Strata.html (${Math.round(html.length / 1024)} KB)`);
}
